import com.pyneon.academy.c.CInterpreter

fun show(label: String, src: String, tests: List<String> = emptyList()) {
    val r = if (tests.isEmpty()) CInterpreter.run(src) else CInterpreter.check(src, tests)
    println("### $label -> ok=${r.ok} type=${r.errorType} stdout=[${r.stdout.replace("\n","\n")}] msg=${r.errorMessage}")
}

