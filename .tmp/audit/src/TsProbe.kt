import com.pyneon.academy.ts.TypeScriptTranspiler

fun t(label: String, src: String) {
    val r = TypeScriptTranspiler.transpile(src)
    println("### $label")
    println("IN : " + src.replace("\n", "\n"))
    println("OUT: " + r.code.replace("\n", "\n"))
}

fun main() {
    t("object literal in call", "function f(o: any) { return o; }\nvar x = 1;\nconsole.log(f({name: x}));")
    t("object literal top", "var x = 1;\nvar o = { name: x, level: 2 };")
    t("arrow returning object", "var x = 1;\nvar mk = () => ({name: x});")
    t("string as cast", "var s = \"this as number is text\";")
    t("string public", "console.log(\"public static void main\");")
    t("class first field", "class Hero {\n  name: string;\n  level: number;\n}")
    t("class after method", "class Hero {\n  greet(): string { return 'hi'; }\n  name: string;\n}")
    t("interface in string", "var s = \"interface Foo {\";\nconsole.log(s);")
    t("interface in comment", "// interface Foo {\nvar a: number = 1;")
    t("function type param", "function run(cb: (x: number) => void): void { cb(1); }")
    t("object in assert call", "assert(intro({name: x, level: 66}) === 'x', 'ok')")
    t("ternary then object", "var a = c ? 1 : 2, y: number = 3;")
    t("generic call", "function id<T>(x: T): T { return x; }\nvar n = id<number>(1);")
    t("template as", "var s = `x as number " + "$" + "{y}`;")
    t("regex colon", "var re = /x: number/;")
    t("destructure type", "const {a, b}: Props = obj;")
    t("for type", "for (let i: number = 0; i < 3; i++) {}")
    t("return type arrow", "var double = (n: number): number => n * 2;")
    t("enum in comment", "// enum Color { Red }\nvar a = 1;")
    t("as const", "var x = [1,2] as const;")
    t("non-null in string", "var s = \"wow!\";")
    t("readonly param", "class A { constructor(readonly x: number) {} }")
    t("optional prop", "interface P { a?: number }\nvar p: P = {};")
    t("generic constraint fn", "function f<T extends object>(x: T): T { return x; }")
    t("object method colon", "var o = { f: function() { return 1; } };")
    t("object method shorthand", "var o = { f(): number { return 1; } };")
    t("type alias multiline", "type Props = {\n a: number;\n};\nvar x: number = 1;")
    t("declare", "declare const x: number;\nvar y = 1;")
    t("string with colon", "var s = 'a: b';")
    t("return object", "function f(): {a: number} { return {a: 1}; }")
}
