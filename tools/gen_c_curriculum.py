def lesson(id_, order, chapter, chapter_name, title, subtitle, xp, blocks, exercise):
    prose = PROSE_TEXT[id_]
    text_index = 0
    merged_blocks = []
    for block in blocks:
        if block["type"] == "text" and text_index < len(prose):
            merged_blocks.append({"type": "text", "text": prose[text_index]})
            text_index += 1
        else:
            merged_blocks.append(block)
    if text_index != len(prose):
        raise SystemExit(f"{id_}: 正文段落数不匹配（block {text_index} / prose {len(prose)}）")
    return {
        "id": id_,
        "order": order,
        "chapter": chapter,
        "chapterName": chapter_name,
        "lang": "c",
        "title": title,
        "subtitle": subtitle,
        "xp": xp,
        "blocks": merged_blocks,
        "exercise": exercise,
    }


