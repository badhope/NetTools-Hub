def write_pack(name, lessons):
    path = PACKS_DIR / f"{name}.json"
    path.write_text(
        json.dumps(lessons, ensure_ascii=False, indent=2) + "\n",
        encoding="utf-8",
        newline="\n",
    )
    return path


def main():
    packs = [
        ("c-basics", basics_pack()),
        ("c-core", core_pack()),
        ("c-advanced", advanced_pack()),
    ]
    total = 0
    cases = 0
    for name, lessons in packs:
        write_pack(name, lessons)
        total += len(lessons)
        cases += sum(len(item["exercise"]["tests"]) for item in lessons)
        print(f"{name}: {len(lessons)} lessons")
    print(f"total {total} lessons, {cases} cases")


if __name__ == "__main__":
    main()
